"""Our own eval harness: run a model on a split and score it against CUAD labels.

Usage:
  uv run python src/eval.py --split valid --run-name B0_zero_shot
  uv run python src/eval.py --split valid --few-shot --run-name B1_few_shot
  uv run python src/eval.py --split valid --adapter adapters/lora_v1 --run-name FT1
"""

import argparse
import json
import re
import time
from collections import defaultdict
from pathlib import Path
from typing import Literal

from mlx_lm import generate, load
from mlx_lm.sample_utils import make_sampler
from pydantic import BaseModel, ValidationError

from prompts import CLAUSE_TYPES, MODEL_ID, build_messages, parse_excerpt

RESULTS = Path("results")
SPAN_MATCH_THRESHOLD = 0.5  # token-overlap F1 needed to count a span as "matched"


class ClauseOutput(BaseModel):
    """The output contract. Anything that doesn't fit this is 'invalid JSON'."""
    clause_type: Literal[tuple(CLAUSE_TYPES)]  # type: ignore[valid-type]
    found: bool
    text: str | None


def parse_output(raw: str) -> ClauseOutput | None:
    """Strict: the whole (stripped) output must be one JSON object matching the schema.
    Extra talk or markdown fences = invalid, because a downstream program couldn't use it."""
    try:
        out = ClauseOutput.model_validate_json(raw.strip())
    except ValidationError:
        return None
    # found=true must come with text, found=false with null; otherwise the answer is self-contradictory
    if out.found != (out.text is not None and out.text.strip() != ""):
        return None
    return out


def ws(s: str) -> str:
    """Collapse whitespace, for a fair 'is this text in the excerpt' check."""
    return re.sub(r"\s+", " ", s).strip()


def token_f1(pred: str, gold: str) -> float:
    """SQuAD-style token overlap F1 (lowercase, word tokens)."""
    p, g = re.findall(r"\w+", pred.lower()), re.findall(r"\w+", gold.lower())
    if not p or not g:
        return 0.0
    gold_counts = defaultdict(int)
    for t in g:
        gold_counts[t] += 1
    common = 0
    for t in p:
        if gold_counts[t] > 0:
            common += 1
            gold_counts[t] -= 1
    if common == 0:
        return 0.0
    precision, recall = common / len(p), common / len(g)
    return 2 * precision * recall / (precision + recall)


def score(preds: list[dict]) -> dict:
    """Metrics for a list of prediction rows (overall or one clause type)."""
    n = len(preds)
    valid = sum(p["valid_json"] for p in preds)
    # An invalid output is treated as found=False: the system would show the user nothing.
    tp = sum(p["gold_found"] and p["pred_found"] for p in preds)
    fp = sum(not p["gold_found"] and p["pred_found"] for p in preds)
    fn = sum(p["gold_found"] and not p["pred_found"] for p in preds)
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    gold_pos = [p for p in preds if p["gold_found"]]
    pred_pos = [p for p in preds if p["pred_found"]]
    span_matches = sum(p["span_f1"] >= SPAN_MATCH_THRESHOLD for p in gold_pos)
    hallucinated = sum(p["hallucinated"] for p in pred_pos)
    return {
        "n": n,
        "valid_json_rate": valid / n,
        "precision": precision, "recall": recall, "f1": f1,
        "tp": tp, "fp": fp, "fn": fn,
        # end-to-end: of all gold clauses, how many did we find AND copy well enough
        "span_match_rate": span_matches / len(gold_pos) if gold_pos else 0.0,
        # of the clauses the model claimed, how many have text that isn't in the excerpt
        "hallucination_rate": hallucinated / len(pred_pos) if pred_pos else 0.0,
        "n_pred_found": len(pred_pos),
        "avg_latency_s": sum(p["latency_s"] for p in preds) / n,
    }


def update_summary():
    """Rebuild results/summary.md from every run file, so the table is never hand-edited."""
    runs = []
    for f in sorted(RESULTS.glob("*.json")):
        d = json.loads(f.read_text())
        if "metrics" in d:
            runs.append(d)
    lines = ["# Results summary", "",
             "Auto-generated by `src/eval.py` from `results/*.json`. Do not edit by hand.", "",
             "| run | split | adapter | prompt | n | valid JSON | precision | recall | F1 | span match | hallucination | latency (s) |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in sorted(runs, key=lambda d: d["created"]):
        m, c = d["metrics"]["overall"], d["config"]
        lines.append(f"| {c['run_name']} | {c['split']} | {c['adapter'] or '-'} | {'few-shot' if c['few_shot'] else 'zero-shot'} | "
                     f"{m['n']} | {m['valid_json_rate']:.1%} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | "
                     f"{m['span_match_rate']:.1%} | {m['hallucination_rate']:.1%} | {m['avg_latency_s']:.2f} |")
    (RESULTS / "summary.md").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=MODEL_ID)
    ap.add_argument("--adapter", default=None, help="path to a LoRA adapter folder")
    ap.add_argument("--split", choices=["valid", "test", "golden"], required=True)
    ap.add_argument("--few-shot", action="store_true", help="baseline B1 prompt")
    ap.add_argument("--run-name", required=True)
    ap.add_argument("--limit", type=int, default=None, help="only first N examples (smoke test)")
    ap.add_argument("--max-tokens", type=int, default=800)  # longest gold clause is ~480 words
    args = ap.parse_args()

    records = [json.loads(line) for line in open(f"data/processed/{args.split}.jsonl")]
    records = records[: args.limit] if args.limit else records

    model, tokenizer = load(args.model, adapter_path=args.adapter)
    sampler = make_sampler(temp=0.0)  # greedy: deterministic, so runs are comparable

    preds = []
    t_start = time.perf_counter()
    for i, r in enumerate(records, 1):
        clause_type = r["meta"]["clause_type"]
        excerpt = parse_excerpt(r["messages"][1]["content"])
        gold = json.loads(r["messages"][2]["content"])
        # Rebuild the prompt from prompts.py (not copied from the file), so B0/B1/FT all share one builder.
        prompt = tokenizer.apply_chat_template(build_messages(clause_type, excerpt, args.few_shot),
                                               add_generation_prompt=True, tokenize=False)
        t0 = time.perf_counter()
        raw = generate(model, tokenizer, prompt=prompt, max_tokens=args.max_tokens, sampler=sampler)
        latency = time.perf_counter() - t0

        out = parse_output(raw)
        pred_found = bool(out and out.found)
        pred_text = out.text if out and out.found else None
        preds.append({
            "idx": i - 1, "title": r["meta"]["title"], "clause_type": clause_type, "hard": r["meta"]["hard"],
            "gold_found": gold["found"], "gold_text": gold["text"],
            "raw_output": raw, "valid_json": out is not None,
            "pred_found": pred_found, "pred_text": pred_text,
            "span_f1": token_f1(pred_text, gold["text"]) if pred_text and gold["text"] else 0.0,
            "hallucinated": bool(pred_text) and ws(pred_text) not in ws(excerpt),
            "latency_s": latency,
        })
        if i % 10 == 0 or i == len(records):
            done = time.perf_counter() - t_start
            print(f"[{i}/{len(records)}] {done:.0f}s elapsed, ~{done / i * (len(records) - i):.0f}s left", flush=True)

    metrics = {"overall": score(preds),
               "per_clause_type": {t: score(ps) for t in CLAUSE_TYPES
                                   if (ps := [p for p in preds if p["clause_type"] == t])}}  # skip types absent (e.g. --limit)
    result = {"created": time.strftime("%Y-%m-%d %H:%M:%S"),
              "config": {**vars(args), "span_match_threshold": SPAN_MATCH_THRESHOLD},
              "metrics": metrics, "predictions": preds}
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / f"{args.run_name}.json").write_text(json.dumps(result, indent=2, ensure_ascii=False))
    update_summary()

    m = metrics["overall"]
    print(f"\n{args.run_name} on {args.split} (n={m['n']}): valid_json={m['valid_json_rate']:.1%} "
          f"P={m['precision']:.3f} R={m['recall']:.3f} F1={m['f1']:.3f} span_match={m['span_match_rate']:.1%} "
          f"halluc={m['hallucination_rate']:.1%} latency={m['avg_latency_s']:.2f}s")
    for t, mt in metrics["per_clause_type"].items():
        print(f"  {t:28s} F1={mt['f1']:.3f} P={mt['precision']:.3f} R={mt['recall']:.3f} "
              f"span={mt['span_match_rate']:.1%} halluc={mt['hallucination_rate']:.1%}")


if __name__ == "__main__":
    main()
